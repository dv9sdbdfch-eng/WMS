class StockCount(IdMixin, Base):
    """A physical count: system quantity -> counted quantity -> review -> approved adjustments.

    Status OPEN (counting) -> SUBMITTED (waiting for review) -> APPROVED, or CANCELLED.
    Nothing changes stock until a user with ``stock.adjust`` approves it; each difference is
    then posted as a normal stock adjustment linked back to its count line.
    """

    __tablename__ = "stock_counts"

    count_number: Mapped[str] = mapped_column(String(30), unique=True, nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="OPEN", index=True)
    location_id: Mapped[int | None] = fk("locations.id")
    description: Mapped[str | None] = mapped_column(String(200))
    notes: Mapped[str | None] = mapped_column(Text)
    created_by_id: Mapped[int] = fk("users.id", nullable=False)
    created_at: Mapped[datetime] = mapped_column(UTCDateTime, default=utcnow, nullable=False, index=True)
    submitted_by_id: Mapped[int | None] = fk("users.id")
    submitted_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    closed_by_id: Mapped[int | None] = fk("users.id")
    closed_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    close_reason: Mapped[str | None] = mapped_column(Text)

    location = relationship("Location", lazy="joined")
    created_by = relationship("User", foreign_keys=[created_by_id], lazy="joined")
    submitted_by = relationship("User", foreign_keys=[submitted_by_id], lazy="joined")
    closed_by = relationship("User", foreign_keys=[closed_by_id], lazy="joined")
    lines: Mapped[list[StockCountLine]] = relationship(
        back_populates="count", order_by="StockCountLine.line_no", cascade="all, delete-orphan"
    )


class StockCountLine(IdMixin, Base):
    __tablename__ = "stock_count_lines"
    __table_args__ = (UniqueConstraint("count_id", "product_id", "bin_id"),)

    count_id: Mapped[int] = fk("stock_counts.id", nullable=False, ondelete="CASCADE")
    line_no: Mapped[int] = mapped_column(Integer, nullable=False)
    product_id: Mapped[int] = fk("products.id", nullable=False)
    bin_id: Mapped[int] = fk("bins.id", nullable=False)
    system_qty: Mapped[Decimal] = mapped_column(Quantity, nullable=False)
    counted_qty: Mapped[Decimal | None] = mapped_column(Quantity)
    counted_by_id: Mapped[int | None] = fk("users.id")
    counted_at: Mapped[datetime | None] = mapped_column(UTCDateTime)
    notes: Mapped[str | None] = mapped_column(Text)
    adjustment_id: Mapped[int | None] = fk("stock_adjustments.id")

    count: Mapped[StockCount] = relationship(back_populates="lines")
    product = relationship("Product", lazy="joined")
    bin = relationship("Bin", lazy="joined")

    @property
    def difference(self) -> Decimal | None:
        return None if self.counted_qty is None else self.counted_qty - self.system_qty
